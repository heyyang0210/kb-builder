  CONSTRAINT UK_KC_TDOMAIN_GROUP UNIQUE (TEAM_GROUP_ID),
  CONSTRAINT CK_KC_TDOMAIN_STATE CHECK (STATE IN ('ACTIVE', 'INACTIVE')),
  CONSTRAINT CK_KC_TDOMAIN_ROWVER CHECK (ROW_VERSION >= 1)
