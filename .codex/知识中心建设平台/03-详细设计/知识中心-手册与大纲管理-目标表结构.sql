CREATE TABLE KC_MANUAL_OUTLINE_VERSION (
  OUTLINE_VERSION_ID BIGINT DEFAULT KC_OUTLINE_SEQ.NEXTVAL NOT NULL,
  OUTLINE_ID BIGINT NOT NULL,
  VERSION_CODE VARCHAR(128) NOT NULL,
  BASE_OUTLINE_VERSION_ID BIGINT,
  CURRENT_RESP_VERSION_ID BIGINT,
  STATE VARCHAR(32) DEFAULT 'DRAFT' NOT NULL,
  SOURCE_TYPE VARCHAR(32) NOT NULL,
  SOURCE_REF VARCHAR(1000),
  SOURCE_FILE_NAME VARCHAR(512),
  SOURCE_SHA256 CHAR(64),
  PARSER_VERSION VARCHAR(64),
  RULE_VERSION VARCHAR(64),
  STRUCTURE_SHA256 CHAR(64) NOT NULL,
  ROW_VERSION BIGINT DEFAULT 1 NOT NULL,
  PUBLISH_REQUEST_ID VARCHAR(128),
  PUBLISH_REASON VARCHAR(1000),
  PUBLISHED_BY VARCHAR(128),
  PUBLISHED_AT TIMESTAMP(6),
  ARCHIVED_AT TIMESTAMP(6),
  CREATED_BY VARCHAR(128) NOT NULL,
  CREATED_AT TIMESTAMP(6) DEFAULT CURRENT_TIMESTAMP NOT NULL,
  UPDATED_BY VARCHAR(128) NOT NULL,
  UPDATED_AT TIMESTAMP(6) DEFAULT CURRENT_TIMESTAMP NOT NULL,
  CONSTRAINT PK_KC_MO_VERSION PRIMARY KEY (OUTLINE_VERSION_ID),
  CONSTRAINT UK_KC_OVERSION_CODE UNIQUE (OUTLINE_ID, VERSION_CODE),
  CONSTRAINT UK_KC_OVERSION_PUBREQ UNIQUE (PUBLISH_REQUEST_ID),
  CONSTRAINT CK_KC_OVERSION_STATE CHECK (
    STATE IN ('DRAFT', 'READY', 'PUBLISHED', 'SUPERSEDED', 'ARCHIVED')
  ),
  CONSTRAINT CK_KC_OVERSION_SOURCE CHECK (
    SOURCE_TYPE IN ('MANUAL', 'IMPORT', 'REVERSE_EXTRACT', 'MIGRATION')
  ),
  CONSTRAINT CK_KC_OVERSION_ROWVER CHECK (ROW_VERSION >= 1),
  CONSTRAINT CK_KC_OVERSION_PUBLISH CHECK (
    (STATE IN ('PUBLISHED', 'SUPERSEDED', 'ARCHIVED') AND PUBLISHED_AT IS NOT NULL)
    OR (STATE IN ('DRAFT', 'READY') AND PUBLISHED_AT IS NULL)
  ),
  CONSTRAINT CK_KC_OVERSION_ARCHIVE CHECK (
    (STATE = 'ARCHIVED' AND ARCHIVED_AT IS NOT NULL)
    OR (STATE <> 'ARCHIVED' AND ARCHIVED_AT IS NULL)
  )
);

