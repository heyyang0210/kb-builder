CREATE TABLE KC_TEAM_GROUP (
  TEAM_GROUP_ID BIGINT DEFAULT KC_RESPONSIBILITY_SEQ.NEXTVAL NOT NULL,
  GROUP_CODE VARCHAR(128) NOT NULL,
  GROUP_NAME VARCHAR(255) NOT NULL,
  GROUP_TYPE VARCHAR(64) NOT NULL,
