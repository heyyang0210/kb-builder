CREATE TABLE KC_MANUAL_OUTLINE_RESP_ITEM (
  RESP_ITEM_ID BIGINT DEFAULT KC_RESPONSIBILITY_SEQ.NEXTVAL NOT NULL,
  RESP_VERSION_ID BIGINT NOT NULL,
  OUTLINE_NODE_ID BIGINT NOT NULL,
  TECH_DOMAIN_ID BIGINT NOT NULL,
  DOMAIN_ROLE VARCHAR(16) NOT NULL,
  OWNER_PRINCIPAL_ID BIGINT,
  BINDING_STATUS VARCHAR(16) DEFAULT 'PENDING' NOT NULL,
  HANDOFF_NOTE VARCHAR(2000),
  CREATED_BY VARCHAR(128) NOT NULL,
  CREATED_AT TIMESTAMP(6) DEFAULT CURRENT_TIMESTAMP NOT NULL,
  UPDATED_BY VARCHAR(128) NOT NULL,
  UPDATED_AT TIMESTAMP(6) DEFAULT CURRENT_TIMESTAMP NOT NULL,
  CONSTRAINT PK_KC_ORESP_ITEM PRIMARY KEY (RESP_ITEM_ID),
  CONSTRAINT UK_KC_ORITEM_DOMAIN UNIQUE (
    RESP_VERSION_ID, OUTLINE_NODE_ID, TECH_DOMAIN_ID
  ),
  CONSTRAINT CK_KC_ORITEM_ROLE CHECK (
    DOMAIN_ROLE IN ('PRIMARY', 'COLLABORATOR')
  ),
  CONSTRAINT CK_KC_ORITEM_BIND CHECK (
    BINDING_STATUS IN ('PENDING', 'BOUND', 'INVALID')
  ),
  CONSTRAINT CK_KC_ORITEM_OWNER CHECK (
    (BINDING_STATUS = 'BOUND' AND OWNER_PRINCIPAL_ID IS NOT NULL)
    OR (BINDING_STATUS <> 'BOUND')
  )
);

CREATE TABLE KC_MANUAL_OUTLINE_CHECK_RUN (
  CHECK_RUN_ID BIGINT DEFAULT KC_OUTLINE_SEQ.NEXTVAL NOT NULL,
  OUTLINE_VERSION_ID BIGINT NOT NULL,
  CHECK_TYPE VARCHAR(32) NOT NULL,
  RULE_VERSION VARCHAR(64) NOT NULL,
  CHECK_STATUS VARCHAR(16) NOT NULL,
  ERROR_COUNT BIGINT DEFAULT 0 NOT NULL,
  WARNING_COUNT BIGINT DEFAULT 0 NOT NULL,
  RESULT_DETAIL CLOB,
  STRUCTURE_SHA256 CHAR(64) NOT NULL,
  REQUESTED_BY VARCHAR(128) NOT NULL,
  STARTED_AT TIMESTAMP(6) DEFAULT CURRENT_TIMESTAMP NOT NULL,
  COMPLETED_AT TIMESTAMP(6),
  CREATED_BY VARCHAR(128) NOT NULL,
  CREATED_AT TIMESTAMP(6) DEFAULT CURRENT_TIMESTAMP NOT NULL,
  UPDATED_BY VARCHAR(128) NOT NULL,
  UPDATED_AT TIMESTAMP(6) DEFAULT CURRENT_TIMESTAMP NOT NULL,
  CONSTRAINT PK_KC_OCHECK_RUN PRIMARY KEY (CHECK_RUN_ID),
  CONSTRAINT CK_KC_OCHECK_TYPE CHECK (
    CHECK_TYPE IN ('IMPORT', 'PREFLIGHT', 'PUBLISH')
  ),
  CONSTRAINT CK_KC_OCHECK_STATUS CHECK (
    CHECK_STATUS IN ('RUNNING', 'PASSED', 'FAILED', 'CANCELLED')
  ),
  CONSTRAINT CK_KC_OCHECK_COUNT CHECK (ERROR_COUNT >= 0 AND WARNING_COUNT >= 0),
  CONSTRAINT CK_KC_OCHECK_TIME CHECK (
    COMPLETED_AT IS NULL OR COMPLETED_AT >= STARTED_AT
  )
);

CREATE TABLE KC_MANUAL_OUTLINE_CHANGE (
  OUTLINE_CHANGE_ID BIGINT DEFAULT KC_OUTLINE_SEQ.NEXTVAL NOT NULL,
  OUTLINE_VERSION_ID BIGINT NOT NULL,
  CHANGE_SEQ BIGINT NOT NULL,
  CHANGE_TYPE VARCHAR(32) NOT NULL,
  NODE_KEY VARCHAR(128),
  BEFORE_SNAPSHOT CLOB,
  AFTER_SNAPSHOT CLOB,
  CHANGE_REASON VARCHAR(1000),
  CREATED_BY VARCHAR(128) NOT NULL,
  CREATED_AT TIMESTAMP(6) DEFAULT CURRENT_TIMESTAMP NOT NULL,
  UPDATED_BY VARCHAR(128) NOT NULL,
  UPDATED_AT TIMESTAMP(6) DEFAULT CURRENT_TIMESTAMP NOT NULL,
  CONSTRAINT PK_KC_MO_CHANGE PRIMARY KEY (OUTLINE_CHANGE_ID),
  CONSTRAINT UK_KC_OCHANGE_SEQ UNIQUE (OUTLINE_VERSION_ID, CHANGE_SEQ),
  CONSTRAINT CK_KC_OCHANGE_SEQ CHECK (CHANGE_SEQ >= 1),
  CONSTRAINT CK_KC_OCHANGE_TYPE CHECK (
    CHANGE_TYPE IN (
      'NODE_ADD', 'NODE_UPDATE', 'NODE_MOVE', 'NODE_DELETE',
      'NODE_SPLIT', 'NODE_MERGE', 'VERSION_TAG_UPDATE'
    )
  ),
  CONSTRAINT CK_KC_OCHANGE_DATA CHECK (
    BEFORE_SNAPSHOT IS NOT NULL OR AFTER_SNAPSHOT IS NOT NULL
  )
);

COMMENT ON TABLE KC_MANUAL IS '产品范围内按名称唯一的手册稳定主对象';
COMMENT ON TABLE KC_MANUAL_OWNER IS '手册主负责人和协同负责人与CAS主体的绑定';
COMMENT ON TABLE KC_MANUAL_OUTLINE IS '与手册一对一的大纲稳定主体，名称和产品从所属手册获取';
COMMENT ON TABLE KC_TECH_DOMAIN IS '大纲责任分工使用的技术领域标准字典；显式引用负责该领域的团队小组';
COMMENT ON TABLE KC_TEAM_GROUP IS '独立的人员团队；团队不反向保存领域外键';
COMMENT ON TABLE KC_TEAM_GROUP_MEMBER IS '团队负责人和普通成员关系、状态及有效期';
COMMENT ON TABLE KC_MANUAL_OUTLINE_VERSION IS '一本手册的完整且可发布的大纲结构版本';
COMMENT ON TABLE KC_MANUAL_OUTLINE_VERSION_TAG IS '大纲版本适用的离散产品版本标签';
COMMENT ON TABLE KC_MANUAL_OUTLINE_NODE IS '大纲版本内的目录和页面节点树';
COMMENT ON TABLE KC_MANUAL_OUTLINE_RESP_VERSION IS '与大纲结构独立版本化的责任映射';
COMMENT ON TABLE KC_MANUAL_OUTLINE_RESP_ITEM IS '页面的主责或协作领域及责任人绑定';
COMMENT ON TABLE KC_MANUAL_OUTLINE_CHECK_RUN IS '导入、预检和发布检查运行结果';
COMMENT ON TABLE KC_MANUAL_OUTLINE_CHANGE IS '候选大纲的节点级结构变更事实';

COMMENT ON COLUMN KC_MANUAL_OUTLINE_NODE.NODE_KEY IS
  '同一业务节点跨大纲版本保持稳定的标识，不使用标题或路径生成身份';
COMMENT ON COLUMN KC_MANUAL_OUTLINE_VERSION.STRUCTURE_SHA256 IS
  '规范化大纲结构的SHA-256，用于预检基线校验和对账';
COMMENT ON COLUMN KC_MANUAL_OUTLINE_RESP_VERSION.MAPPING_SHA256 IS
  '规范化责任映射的SHA-256，用于版本对账';
COMMENT ON COLUMN KC_MANUAL_OWNER.PRINCIPAL_ID IS
  'CAS身份映射后的平台稳定主体ID，姓名不作为身份保存';
COMMENT ON COLUMN KC_TEAM_GROUP.ROW_VERSION IS
  '名册变更的乐观锁版本；成员保存、版本递增和审计必须同一事务';

-- 一个有效团队必须且只能有一个有效LEADER。带状态和有效期的条件唯一性
-- 由名册保存事务在锁定团队后校验，不能只依赖普通唯一约束。

-- 逻辑关联列和主要查询路径索引；本基线不创建物理外键。
CREATE INDEX IX_KC_MANUAL_SCOPE
  ON KC_MANUAL (ORG_UNIT_ID, PRODUCT_ID, STATE, UPDATED_AT);

CREATE INDEX IX_KC_MOWNER_PERSON
  ON KC_MANUAL_OWNER (PRINCIPAL_ID, OWNER_ROLE);

CREATE INDEX IX_KC_MOUTLINE_CURRENT
  ON KC_MANUAL_OUTLINE (CURRENT_OUTLINE_VERSION_ID);

CREATE INDEX IX_KC_TGROUP_SCOPE
  ON KC_TEAM_GROUP (GROUP_TYPE, ORG_UNIT_ID, STATE, UPDATED_AT);

CREATE INDEX IX_KC_TGMEMBER_PERSON
  ON KC_TEAM_GROUP_MEMBER (PRINCIPAL_ID, STATE);

CREATE INDEX IX_KC_TGMEMBER_GROUP
  ON KC_TEAM_GROUP_MEMBER (TEAM_GROUP_ID, STATE, MEMBER_ROLE);


CREATE INDEX IX_KC_OVERSION_OUTLINE
  ON KC_MANUAL_OUTLINE_VERSION (OUTLINE_ID, STATE, UPDATED_AT);

CREATE INDEX IX_KC_OVERSION_BASE
  ON KC_MANUAL_OUTLINE_VERSION (BASE_OUTLINE_VERSION_ID);

CREATE INDEX IX_KC_OVTAG_PRODUCT
  ON KC_MANUAL_OUTLINE_VERSION_TAG (PRODUCT_VERSION_ID);

CREATE INDEX IX_KC_ONODE_TREE
  ON KC_MANUAL_OUTLINE_NODE (OUTLINE_VERSION_ID, PARENT_NODE_ID, NODE_TYPE, SORT_NO);

CREATE INDEX IX_KC_ONODE_TYPE
  ON KC_MANUAL_OUTLINE_NODE (OUTLINE_VERSION_ID, NODE_TYPE);

CREATE INDEX IX_KC_ORVERSION_OUTLINE
  ON KC_MANUAL_OUTLINE_RESP_VERSION (OUTLINE_VERSION_ID, STATE, VERSION_NO);

CREATE INDEX IX_KC_ORVERSION_BASE
  ON KC_MANUAL_OUTLINE_RESP_VERSION (BASE_RESP_VERSION_ID);

CREATE INDEX IX_KC_ORITEM_NODE
  ON KC_MANUAL_OUTLINE_RESP_ITEM (OUTLINE_NODE_ID, DOMAIN_ROLE);

CREATE INDEX IX_KC_ORITEM_DOMAIN
  ON KC_MANUAL_OUTLINE_RESP_ITEM (TECH_DOMAIN_ID, OWNER_PRINCIPAL_ID);

CREATE INDEX IX_KC_OCHECK_OUTLINE
  ON KC_MANUAL_OUTLINE_CHECK_RUN (OUTLINE_VERSION_ID, CHECK_TYPE, STARTED_AT);

CREATE INDEX IX_KC_OCHANGE_OUTLINE
  ON KC_MANUAL_OUTLINE_CHANGE (OUTLINE_VERSION_ID, CHANGE_TYPE, CHANGE_SEQ);
