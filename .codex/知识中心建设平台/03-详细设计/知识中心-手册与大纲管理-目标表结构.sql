CREATE TABLE KC_TEAM_GROUP_MEMBER (
  TEAM_GROUP_MEMBER_ID BIGINT DEFAULT KC_RESPONSIBILITY_SEQ.NEXTVAL NOT NULL,
  TEAM_GROUP_ID BIGINT NOT NULL,
  PRINCIPAL_ID BIGINT NOT NULL,
  MEMBER_ROLE VARCHAR(16) NOT NULL,
  STATE VARCHAR(16) DEFAULT 'ACTIVE' NOT NULL,
  EFFECTIVE_FROM TIMESTAMP(6) DEFAULT CURRENT_TIMESTAMP NOT NULL,
  EFFECTIVE_TO TIMESTAMP(6),
  CREATED_BY VARCHAR(128) NOT NULL,
  CREATED_AT TIMESTAMP(6) DEFAULT CURRENT_TIMESTAMP NOT NULL,
  UPDATED_BY VARCHAR(128) NOT NULL,
  UPDATED_AT TIMESTAMP(6) DEFAULT CURRENT_TIMESTAMP NOT NULL,
  CONSTRAINT PK_KC_TGROUP_MEMBER PRIMARY KEY (TEAM_GROUP_MEMBER_ID),
  CONSTRAINT UK_KC_TGMEMBER_PERSON UNIQUE (TEAM_GROUP_ID, PRINCIPAL_ID),
  CONSTRAINT CK_KC_TGMEMBER_ROLE CHECK (MEMBER_ROLE IN ('LEADER', 'MEMBER')),
  CONSTRAINT CK_KC_TGMEMBER_STATE CHECK (STATE IN ('ACTIVE', 'INACTIVE')),
  CONSTRAINT CK_KC_TGMEMBER_TIME CHECK (
    EFFECTIVE_TO IS NULL OR EFFECTIVE_TO > EFFECTIVE_FROM
  )
