-- 知识中心：手册管理与大纲管理目标 DDL
-- 设计版本：1.8.0
-- 适用数据库：YashanDB
-- 说明：本文件用于从空 schema 创建目标模型，不是现网原地升级脚本。
-- ID 规则：内部主键、表间关联键及权威目录 ID 使用 BIGINT；业务编码和幂等请求号使用字符串。

CREATE SEQUENCE KC_MANUAL_SEQ START WITH 1 INCREMENT BY 1;
CREATE SEQUENCE KC_OUTLINE_SEQ START WITH 1 INCREMENT BY 1;
CREATE SEQUENCE KC_RESPONSIBILITY_SEQ START WITH 1 INCREMENT BY 1;

CREATE TABLE KC_MANUAL (
  MANUAL_ID BIGINT DEFAULT KC_MANUAL_SEQ.NEXTVAL NOT NULL,
  MANUAL_CODE VARCHAR(128) NOT NULL,
  MANUAL_NAME VARCHAR(255) NOT NULL,
  PRODUCT_ID BIGINT NOT NULL,
  PRODUCT_NAME VARCHAR(128) NOT NULL,
  ORG_UNIT_ID BIGINT,
  MANUAL_KIND VARCHAR(32) NOT NULL,
  IS_EXTERNALLY_VISIBLE CHAR(1) DEFAULT 'N' NOT NULL,
  STATE VARCHAR(32) DEFAULT 'DRAFT' NOT NULL,
  SUMMARY CLOB,
  ROW_VERSION BIGINT DEFAULT 1 NOT NULL,
  ARCHIVED_AT TIMESTAMP(6),
  CREATED_BY VARCHAR(128) NOT NULL,
  CREATED_AT TIMESTAMP(6) DEFAULT CURRENT_TIMESTAMP NOT NULL,
  UPDATED_BY VARCHAR(128) NOT NULL,
  UPDATED_AT TIMESTAMP(6) DEFAULT CURRENT_TIMESTAMP NOT NULL,
  CONSTRAINT PK_KC_MANUAL PRIMARY KEY (MANUAL_ID),
  CONSTRAINT UK_KC_MANUAL_PRODUCT_NAME UNIQUE (PRODUCT_ID, MANUAL_NAME),
  CONSTRAINT UK_KC_MANUAL_PRODUCT_CODE UNIQUE (PRODUCT_ID, MANUAL_CODE),
  CONSTRAINT CK_KC_MANUAL_KIND CHECK (
    MANUAL_KIND IN ('ATOMIC', 'COMPOSITE', 'TRAINING', 'WHITEPAPER', 'OTHER')
  ),
  CONSTRAINT CK_KC_MANUAL_VISIBLE CHECK (IS_EXTERNALLY_VISIBLE IN ('Y', 'N')),
  CONSTRAINT CK_KC_MANUAL_STATE CHECK (
    STATE IN ('DRAFT', 'ACTIVE', 'FROZEN', 'ARCHIVED')
  ),
  CONSTRAINT CK_KC_MANUAL_ROWVER CHECK (ROW_VERSION >= 1),
  CONSTRAINT CK_KC_MANUAL_ARCHIVE CHECK (
    (STATE = 'ARCHIVED' AND ARCHIVED_AT IS NOT NULL)
    OR (STATE <> 'ARCHIVED' AND ARCHIVED_AT IS NULL)
  )
);

CREATE TABLE KC_MANUAL_OWNER (
  MANUAL_OWNER_ID BIGINT DEFAULT KC_MANUAL_SEQ.NEXTVAL NOT NULL,
  MANUAL_ID BIGINT NOT NULL,
  OWNER_ROLE VARCHAR(16) NOT NULL,
  PRINCIPAL_ID BIGINT NOT NULL,
  CREATED_BY VARCHAR(128) NOT NULL,
  CREATED_AT TIMESTAMP(6) DEFAULT CURRENT_TIMESTAMP NOT NULL,
  UPDATED_BY VARCHAR(128) NOT NULL,
  UPDATED_AT TIMESTAMP(6) DEFAULT CURRENT_TIMESTAMP NOT NULL,
  CONSTRAINT PK_KC_MANUAL_OWNER PRIMARY KEY (MANUAL_OWNER_ID),
  CONSTRAINT UK_KC_MOWNER_ROLE UNIQUE (MANUAL_ID, OWNER_ROLE),
  CONSTRAINT UK_KC_MOWNER_PERSON UNIQUE (MANUAL_ID, PRINCIPAL_ID),
  CONSTRAINT CK_KC_MOWNER_ROLE CHECK (OWNER_ROLE IN ('PRIMARY', 'DEPUTY'))
);

CREATE TABLE KC_MANUAL_OUTLINE (
  OUTLINE_ID BIGINT DEFAULT KC_MANUAL_SEQ.NEXTVAL NOT NULL,
  MANUAL_ID BIGINT NOT NULL,
  CURRENT_OUTLINE_VERSION_ID BIGINT,
  CREATED_BY VARCHAR(128) NOT NULL,
  CREATED_AT TIMESTAMP(6) DEFAULT CURRENT_TIMESTAMP NOT NULL,
  UPDATED_BY VARCHAR(128) NOT NULL,
  UPDATED_AT TIMESTAMP(6) DEFAULT CURRENT_TIMESTAMP NOT NULL,
  CONSTRAINT PK_KC_MANUAL_OUTLINE PRIMARY KEY (OUTLINE_ID),
  CONSTRAINT UK_KC_MOUTLINE_MANUAL UNIQUE (MANUAL_ID)
);

CREATE TABLE KC_TECH_DOMAIN (
