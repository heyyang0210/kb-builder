CREATE TABLE MANUAL_OUTLINE_NODES (
  ID VARCHAR(256) PRIMARY KEY,
  MANUAL_ID VARCHAR(128) NOT NULL,
  OUTLINE_VERSION_ID VARCHAR(128) NOT NULL,
  PARENT_ID VARCHAR(256),
  NODE_TYPE VARCHAR(32) NOT NULL,
  SOURCE_ID VARCHAR(128),
  TITLE VARCHAR(255) NOT NULL,
  DESCRIPTION CLOB,
  OUTLINE_LEVEL BIGINT NOT NULL,
  OUTLINE_PATH VARCHAR(1000) NOT NULL,
  ORDER_INDEX BIGINT NOT NULL,
  CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
  UPDATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
  CONSTRAINT CK_OUTLINE_NODE_TYPE CHECK (NODE_TYPE IN ('directory', 'document'))
);
