-- PingCode business version to GitLab branch. Each edit creates a new revision row.
CREATE TABLE KC_GITLAB_VERSION_MAPPING (
  MAPPING_ID BIGINT DEFAULT KC_PLATFORM_SEQ.NEXTVAL NOT NULL,
  REVISION_OF_ID BIGINT,
  GITLAB_CONNECTION_ID BIGINT NOT NULL,
  PINGCODE_PRODUCT_CODE VARCHAR(64) NOT NULL,
  MATCH_KIND VARCHAR(8) NOT NULL,
  PINGCODE_VERSION VARCHAR(128),
  VERSION_KEY VARCHAR(128) NOT NULL,
  BRANCH_NAME VARCHAR(255) NOT NULL,
  STATE VARCHAR(16) DEFAULT 'DRAFT' NOT NULL,
  ACTIVE_SLOT VARCHAR(64) NOT NULL,
  ROW_VERSION BIGINT DEFAULT 1 NOT NULL,
  CREATED_BY VARCHAR(128) NOT NULL,
  CREATED_AT TIMESTAMP(6) DEFAULT CURRENT_TIMESTAMP NOT NULL,
  UPDATED_BY VARCHAR(128) NOT NULL,
  UPDATED_AT TIMESTAMP(6) DEFAULT CURRENT_TIMESTAMP NOT NULL,
  CONSTRAINT PK_KC_GLVERMAP PRIMARY KEY (MAPPING_ID),
  CONSTRAINT UK_KC_GLVERMAP_SLOT UNIQUE
    (GITLAB_CONNECTION_ID, PINGCODE_PRODUCT_CODE, MATCH_KIND, VERSION_KEY, ACTIVE_SLOT),
  CONSTRAINT CK_KC_GLVERMAP_KIND CHECK (MATCH_KIND IN ('EXACT', 'ALL')),
  CONSTRAINT CK_KC_GLVERMAP_VERSION CHECK
    ((MATCH_KIND = 'ALL' AND PINGCODE_VERSION IS NULL AND VERSION_KEY = '@ALL@') OR
     (MATCH_KIND = 'EXACT' AND PINGCODE_VERSION IS NOT NULL AND VERSION_KEY = PINGCODE_VERSION)),
  CONSTRAINT CK_KC_GLVERMAP_STATE CHECK (STATE IN ('DRAFT', 'ACTIVE', 'SUPERSEDED', 'DISABLED')),
  CONSTRAINT CK_KC_GLVERMAP_SLOT CHECK
    ((STATE = 'ACTIVE' AND ACTIVE_SLOT = 'ACTIVE') OR
     (STATE <> 'ACTIVE' AND ACTIVE_SLOT <> 'ACTIVE')),
  CONSTRAINT CK_KC_GLVERMAP_ROWVER CHECK (ROW_VERSION >= 1)
);

CREATE INDEX IX_KC_GLVERMAP_LIST ON KC_GITLAB_VERSION_MAPPING
  (GITLAB_CONNECTION_ID, PINGCODE_PRODUCT_CODE, STATE, UPDATED_AT);
CREATE INDEX IX_KC_GLVERMAP_REVISION ON KC_GITLAB_VERSION_MAPPING (REVISION_OF_ID);

CREATE TABLE KC_GITLAB_VERSION_MAPPING_EVENT (
  EVENT_ID BIGINT DEFAULT KC_PLATFORM_SEQ.NEXTVAL NOT NULL,
  MAPPING_ID BIGINT NOT NULL,
  EVENT_ACTION VARCHAR(16) NOT NULL,
  OLD_STATE VARCHAR(16),
  NEW_STATE VARCHAR(16) NOT NULL,
  ACTOR VARCHAR(128) NOT NULL,
  OCCURRED_AT TIMESTAMP(6) DEFAULT CURRENT_TIMESTAMP NOT NULL,
  CONSTRAINT PK_KC_GLVERMAP_EVENT PRIMARY KEY (EVENT_ID),
  CONSTRAINT CK_KC_GLVERMAP_EVENT_ACTION CHECK (EVENT_ACTION IN ('CREATE', 'EDIT', 'REVISE', 'ACTIVATE', 'DISABLE'))
);
CREATE INDEX IX_KC_GLVERMAP_EVENT ON KC_GITLAB_VERSION_MAPPING_EVENT (MAPPING_ID, OCCURRED_AT);
