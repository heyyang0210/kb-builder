CREATE TABLE MANUAL_BUILD_TASKS (
  ID VARCHAR(256) PRIMARY KEY,
  MANUAL_ID VARCHAR(128) NOT NULL,
  OUTLINE_VERSION_ID VARCHAR(128) NOT NULL,
  TECH_DOMAIN_ID VARCHAR(128) NOT NULL,
  DOMAIN_LEADER_ID VARCHAR(128),
  DOMAIN_LEADER_NAME VARCHAR(255),
  STATE VARCHAR(32) DEFAULT 'open' NOT NULL,
  PUBLISHED_AT VARCHAR(64),
  CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
  UPDATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
  CONSTRAINT UK_MANUAL_BUILD_TASK UNIQUE (OUTLINE_VERSION_ID, TECH_DOMAIN_ID)
);
