CREATE TABLE MANUAL_BUILD_TASK_ITEMS (
  ID VARCHAR(256) PRIMARY KEY,
  TASK_ID VARCHAR(256) NOT NULL,
  MANUAL_ID VARCHAR(128) NOT NULL,
  DOCUMENT_ID VARCHAR(256) NOT NULL,
  OUTLINE_NODE_ID VARCHAR(256) NOT NULL,
  TECH_DOMAIN_ID VARCHAR(128) NOT NULL,
  ASSIGNEE_ID VARCHAR(128),
  ASSIGNEE_NAME VARCHAR(255),
  STATUS VARCHAR(32) DEFAULT 'unassigned' NOT NULL,
  ASSIGNED_BY VARCHAR(128),
  ASSIGNED_AT VARCHAR(64),
  CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
  UPDATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
  CONSTRAINT UK_BUILD_TASK_ITEM UNIQUE (TASK_ID, DOCUMENT_ID, TECH_DOMAIN_ID)
);
