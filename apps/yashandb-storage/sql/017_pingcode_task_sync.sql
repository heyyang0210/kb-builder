-- Pingcode source synchronization and per-task storage. No existing rows are migrated here.
CREATE TABLE KC_DOCUMENT_TASK (
  TASK_NUMBER VARCHAR(64) NOT NULL,
  PAYLOAD CLOB NOT NULL,
  ROW_VERSION BIGINT DEFAULT 1 NOT NULL,
  OWNER_ID VARCHAR(128),
  PRODUCT_CODE VARCHAR(128),
  BUSINESS_VERSION VARCHAR(128),
  TASK_STATUS VARCHAR(32) NOT NULL,
  ATTENTION VARCHAR(16) DEFAULT 'NORMAL' NOT NULL,
  SOURCE_TYPE VARCHAR(16),
  PRIMARY_SOURCE_ID VARCHAR(64),
  DESCRIPTION VARCHAR(2000),
  UPDATED_AT TIMESTAMP(6) DEFAULT CURRENT_TIMESTAMP NOT NULL,
  CONSTRAINT PK_KC_DOCUMENT_TASK PRIMARY KEY (TASK_NUMBER),
  CONSTRAINT CK_KC_TASK_ATTENTION CHECK (ATTENTION IN ('NORMAL', 'SECONDARY'))
);
CREATE TABLE KC_DOCUMENT_TASK_CONFIG (
  CONFIG_KEY VARCHAR(32) NOT NULL,
  PAYLOAD CLOB NOT NULL,
  ROW_VERSION BIGINT DEFAULT 1 NOT NULL,
  CONSTRAINT PK_KC_TASK_CONFIG PRIMARY KEY (CONFIG_KEY)
);
CREATE INDEX IX_KC_TASK_LIST ON KC_DOCUMENT_TASK (ATTENTION, TASK_STATUS, UPDATED_AT);
CREATE INDEX IX_KC_TASK_OWNER ON KC_DOCUMENT_TASK (OWNER_ID, ATTENTION, UPDATED_AT);
CREATE INDEX IX_KC_TASK_TYPE ON KC_DOCUMENT_TASK (SOURCE_TYPE, ATTENTION, UPDATED_AT);

CREATE TABLE KC_DOCUMENT_TASK_ACTOR (
  TASK_NUMBER VARCHAR(64) NOT NULL,
  PRINCIPAL_ID VARCHAR(128) NOT NULL,
  ACTOR_ROLE VARCHAR(16) NOT NULL,
  CONSTRAINT PK_KC_TASK_ACTOR PRIMARY KEY (TASK_NUMBER, PRINCIPAL_ID, ACTOR_ROLE),
  CONSTRAINT CK_KC_TASK_ACTOR_ROLE CHECK (ACTOR_ROLE IN ('OWNER', 'HANDBOOK', 'DOCUMENT'))
);
CREATE INDEX IX_KC_TASK_ACTOR_MINE ON KC_DOCUMENT_TASK_ACTOR (PRINCIPAL_ID, TASK_NUMBER);

CREATE TABLE KC_DOCUMENT_TASK_HANDBOOK (
  TASK_NUMBER VARCHAR(64) NOT NULL,
  HANDBOOK_ID VARCHAR(128) NOT NULL,
  CONSTRAINT PK_KC_TASK_HANDBOOK PRIMARY KEY (TASK_NUMBER, HANDBOOK_ID)
);
CREATE INDEX IX_KC_TASK_HANDBOOK_ID ON KC_DOCUMENT_TASK_HANDBOOK (HANDBOOK_ID, TASK_NUMBER);

CREATE TABLE KC_DOCUMENT_TASK_REVIEW (
  REVIEW_TASK_ID VARCHAR(128) NOT NULL,
  TASK_NUMBER VARCHAR(64) NOT NULL,
  CONSTRAINT PK_KC_TASK_REVIEW PRIMARY KEY (REVIEW_TASK_ID, TASK_NUMBER)
);

CREATE TABLE KC_DOCUMENT_TASK_WRITE (
  IDEMPOTENCY_KEY VARCHAR(320) NOT NULL,
  REQUEST_SHA256 CHAR(64) NOT NULL,
  RESULT_PAYLOAD CLOB NOT NULL,
  TASK_NUMBER VARCHAR(64) NOT NULL,
  CREATED_AT TIMESTAMP(6) DEFAULT CURRENT_TIMESTAMP NOT NULL,
  CONSTRAINT PK_KC_TASK_WRITE PRIMARY KEY (IDEMPOTENCY_KEY)
);
CREATE INDEX IX_KC_TASK_WRITE_NUMBER ON KC_DOCUMENT_TASK_WRITE (TASK_NUMBER);

-- Kept separate from the schema version: confirmation is enabled only after
-- the legacy aggregate has been backed up, migrated, and reconciled.
CREATE TABLE KC_TASK_MIGRATION (
  MIGRATION_ID VARCHAR(64) NOT NULL,
  MIGRATION_STATUS VARCHAR(16) NOT NULL,
  LEGACY_REVISION BIGINT NOT NULL,
  LEGACY_SHA256 CHAR(64) NOT NULL,
  TASK_COUNT BIGINT NOT NULL,
  VERIFIED_AT TIMESTAMP(6) NOT NULL,
  CONSTRAINT PK_KC_TASK_MIGRATION PRIMARY KEY (MIGRATION_ID),
  CONSTRAINT CK_KC_TASK_MIGRATION_STATUS CHECK (MIGRATION_STATUS IN ('VERIFIED', 'ACTIVE'))
);

CREATE TABLE KC_PINGCODE_SOURCE (
  SOURCE_ID VARCHAR(64) NOT NULL,
  SOURCE_NAME VARCHAR(255) NOT NULL,
  SOURCE_TYPE VARCHAR(16) NOT NULL,
  SOURCE_URL VARCHAR(2000) NOT NULL,
  CONNECTION_ID VARCHAR(128) NOT NULL,
  SOURCE_STATE VARCHAR(16) DEFAULT 'ACTIVE' NOT NULL,
  ROW_VERSION BIGINT DEFAULT 1 NOT NULL,
  LAST_CONFIRMED_RUN VARCHAR(64),
  CREATED_BY VARCHAR(128) NOT NULL,
  CREATED_AT TIMESTAMP(6) DEFAULT CURRENT_TIMESTAMP NOT NULL,
  UPDATED_AT TIMESTAMP(6) DEFAULT CURRENT_TIMESTAMP NOT NULL,
  CONSTRAINT PK_KC_PC_SOURCE PRIMARY KEY (SOURCE_ID),
  CONSTRAINT UK_KC_PC_SOURCE_URL UNIQUE (CONNECTION_ID, SOURCE_TYPE, SOURCE_URL),
  CONSTRAINT CK_KC_PC_SOURCE_TYPE CHECK (SOURCE_TYPE IN ('REQUIREMENT', 'TICKET')),
  CONSTRAINT CK_KC_PC_SOURCE_STATE CHECK (SOURCE_STATE IN ('ACTIVE', 'DISABLED'))
);

CREATE TABLE KC_PINGCODE_RUN (
  RUN_ID VARCHAR(64) NOT NULL,
  SOURCE_ID VARCHAR(64) NOT NULL,
  SOURCE_REVISION BIGINT NOT NULL,
  RUN_STATUS VARCHAR(24) NOT NULL,
  SOURCE_VERSION VARCHAR(255),
  CRITERIA_SHA256 CHAR(64),
  PREVIEW_DIGEST CHAR(64),
  TASK_REVISION_DIGEST CHAR(64),
  PAGE_COUNT BIGINT,
  ROW_COUNT BIGINT,
  SR_COUNT BIGINT,
  NEW_COUNT BIGINT,
  CHANGED_COUNT BIGINT,
  UNCHANGED_COUNT BIGINT,
  REMOVED_COUNT BIGINT,
  IR_COUNT BIGINT,
  UNLINKED_IR_COUNT BIGINT,
  PAGES_READ BIGINT DEFAULT 0 NOT NULL,
  ROWS_READ BIGINT DEFAULT 0 NOT NULL,
  ERROR_CODE VARCHAR(64),
  CREATED_BY VARCHAR(128) NOT NULL,
  CREATED_AT TIMESTAMP(6) DEFAULT CURRENT_TIMESTAMP NOT NULL,
  FINISHED_AT TIMESTAMP(6),
  CONFIRMED_AT TIMESTAMP(6),
  CONSTRAINT PK_KC_PC_RUN PRIMARY KEY (RUN_ID),
  CONSTRAINT CK_KC_PC_RUN_STATUS CHECK (RUN_STATUS IN ('COLLECTING', 'AWAITING_CONFIRM', 'CONFIRMED', 'CONFIRMED_MISSING_IMAGES', 'FAILED', 'CANCELLED'))
);
CREATE INDEX IX_KC_PC_RUN_SOURCE ON KC_PINGCODE_RUN (SOURCE_ID, CREATED_AT);

CREATE TABLE KC_PINGCODE_SNAPSHOT (
  RUN_ID VARCHAR(64) NOT NULL,
  SR_NUMBER VARCHAR(64) NOT NULL,
  UPSTREAM_ID VARCHAR(128) NOT NULL,
  SHORT_ID VARCHAR(128) NOT NULL,
  TITLE VARCHAR(2000),
  BODY_MARKDOWN CLOB,
  BODY_SHA256 CHAR(64),
  SOURCE_UPDATED_AT VARCHAR(64),
  RESOURCE_VERSION BIGINT DEFAULT 0 NOT NULL,
  RESOURCE_STATE VARCHAR(16) DEFAULT 'COMPLETE' NOT NULL,
  CONSTRAINT PK_KC_PC_SNAPSHOT PRIMARY KEY (RUN_ID, SR_NUMBER),
  CONSTRAINT CK_KC_PC_RESOURCE_STATE CHECK (RESOURCE_STATE IN ('COMPLETE', 'MISSING'))
);
CREATE INDEX IX_KC_PC_SNAPSHOT_SR ON KC_PINGCODE_SNAPSHOT (SR_NUMBER, RUN_ID);

CREATE TABLE KC_PINGCODE_IR_SNAPSHOT (
  RUN_ID VARCHAR(64) NOT NULL,
  IR_NUMBER VARCHAR(64) NOT NULL,
  UPSTREAM_ID VARCHAR(128) NOT NULL,
  RELATED_SR_COUNT BIGINT NOT NULL,
  CONSTRAINT PK_KC_PC_IR_SNAPSHOT PRIMARY KEY (RUN_ID, IR_NUMBER)
);

CREATE TABLE KC_PINGCODE_IR_RELATION (
  RUN_ID VARCHAR(64) NOT NULL,
  SR_NUMBER VARCHAR(64) NOT NULL,
  IR_NUMBER VARCHAR(64) NOT NULL,
  CONSTRAINT PK_KC_PC_IR PRIMARY KEY (RUN_ID, SR_NUMBER, IR_NUMBER)
);
CREATE INDEX IX_KC_PC_IR_LOOKUP ON KC_PINGCODE_IR_RELATION (IR_NUMBER, SR_NUMBER);

CREATE TABLE KC_PINGCODE_TASK_SOURCE (
  SR_NUMBER VARCHAR(64) NOT NULL,
  SOURCE_ID VARCHAR(64) NOT NULL,
  LAST_RUN_ID VARCHAR(64) NOT NULL,
  PRESENT CHAR(1) DEFAULT 'Y' NOT NULL,
  IS_PRIMARY CHAR(1) DEFAULT 'N' NOT NULL,
  CONSTRAINT PK_KC_PC_TASK_SOURCE PRIMARY KEY (SR_NUMBER, SOURCE_ID),
  CONSTRAINT CK_KC_PC_PRESENT CHECK (PRESENT IN ('Y', 'N')),
  CONSTRAINT CK_KC_PC_PRIMARY CHECK (IS_PRIMARY IN ('Y', 'N'))
);
CREATE INDEX IX_KC_PC_SOURCE_TASK ON KC_PINGCODE_TASK_SOURCE (SOURCE_ID, PRESENT);

CREATE TABLE KC_PINGCODE_CHANGE (
  RUN_ID VARCHAR(64) NOT NULL,
  SR_NUMBER VARCHAR(64) NOT NULL,
  FIELD_NAME VARCHAR(128) NOT NULL,
  BEFORE_VALUE CLOB,
  AFTER_VALUE CLOB,
  CONSTRAINT PK_KC_PC_CHANGE PRIMARY KEY (RUN_ID, SR_NUMBER, FIELD_NAME)
);
CREATE INDEX IX_KC_PC_CHANGE_SR ON KC_PINGCODE_CHANGE (SR_NUMBER, RUN_ID);

CREATE TABLE KC_PINGCODE_RESOURCE (
  RUN_ID VARCHAR(64) NOT NULL,
  SR_NUMBER VARCHAR(64) NOT NULL,
  RESOURCE_ID CHAR(64) NOT NULL,
  RESOURCE_VERSION BIGINT DEFAULT 0 NOT NULL,
  RESOURCE_PATH VARCHAR(500),
  CONTENT_TYPE VARCHAR(100),
  BYTE_COUNT BIGINT,
  RESOURCE_STATE VARCHAR(16) NOT NULL,
  ERROR_CODE VARCHAR(64),
  CONSTRAINT PK_KC_PC_RESOURCE PRIMARY KEY (RUN_ID, SR_NUMBER, RESOURCE_ID, RESOURCE_VERSION),
  CONSTRAINT CK_KC_PC_RES_STATE CHECK (RESOURCE_STATE IN ('READY', 'FAILED'))
);
