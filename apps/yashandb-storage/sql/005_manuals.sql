CREATE TABLE MANUALS (
  ID VARCHAR(128) PRIMARY KEY,
  CODE VARCHAR(128) NOT NULL UNIQUE,
  TITLE VARCHAR(255) NOT NULL,
  PRODUCT_ID VARCHAR(128),
  OWNER_A_ID VARCHAR(128),
  OWNER_A_NAME VARCHAR(255),
  OWNER_B_ID VARCHAR(128),
  OWNER_B_NAME VARCHAR(255),
  DEPARTMENT_ID VARCHAR(128),
  CURRENT_OUTLINE_VERSION_ID VARCHAR(128),
  STATUS VARCHAR(64),
  ARCHIVED_AT VARCHAR(64),
  ASSET_VERSION BIGINT DEFAULT 1 NOT NULL,
  SUMMARY CLOB,
  LEGACY_PAYLOAD CLOB,
  LEGACY_AUDITS CLOB,
  CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
  UPDATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);
