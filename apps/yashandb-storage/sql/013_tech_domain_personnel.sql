CREATE TABLE TECH_DOMAIN_PERSONNEL (
  ID VARCHAR(128) PRIMARY KEY,
  DOMAIN_ID VARCHAR(128) NOT NULL,
  PERSON_ID VARCHAR(128) NOT NULL,
  PERSON_NAME VARCHAR(255) NOT NULL,
  ROLE_CODE VARCHAR(32) NOT NULL,
  STATUS VARCHAR(32) DEFAULT 'active' NOT NULL,
  CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
  UPDATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
  CONSTRAINT CK_TECH_DOMAIN_PERSONNEL_ROLE CHECK (ROLE_CODE IN ('leader', 'member')),
  CONSTRAINT UK_TECH_DOMAIN_PERSON UNIQUE (DOMAIN_ID, PERSON_ID)
);
