CREATE TABLE KC_PLATFORM_PRINCIPAL (
  PRINCIPAL_ID BIGINT DEFAULT KC_BUSINESS_ID_SEQ.NEXTVAL NOT NULL,
  DISPLAY_NAME VARCHAR(128) NOT NULL,
  CAS_LOGIN_NAME VARCHAR(128),
  STATE VARCHAR(16) DEFAULT 'ACTIVE' NOT NULL,
  FIRST_LOGIN_AT TIMESTAMP(6),
  LAST_LOGIN_AT TIMESTAMP(6),
  ROW_VERSION BIGINT DEFAULT 1 NOT NULL,
  CREATED_BY VARCHAR(128) NOT NULL,
  CREATED_AT TIMESTAMP(6) DEFAULT CURRENT_TIMESTAMP NOT NULL,
  UPDATED_BY VARCHAR(128) NOT NULL,
  UPDATED_AT TIMESTAMP(6) DEFAULT CURRENT_TIMESTAMP NOT NULL,
  CONSTRAINT PK_KC_PRINCIPAL PRIMARY KEY (PRINCIPAL_ID),
  CONSTRAINT UK_KC_PRINCIPAL_LOGIN UNIQUE (CAS_LOGIN_NAME),
  CONSTRAINT CK_KC_PRINCIPAL_STATE CHECK (STATE IN ('ACTIVE', 'INACTIVE')),
  CONSTRAINT CK_KC_PRINCIPAL_ROWVER CHECK (ROW_VERSION >= 1),
  CONSTRAINT CK_KC_PRINCIPAL_LOGIN CHECK (
    CAS_LOGIN_NAME IS NULL OR LENGTH(TRIM(CAS_LOGIN_NAME)) > 0
  )
);

CREATE INDEX IX_KC_PRINCIPAL_NAME
  ON KC_PLATFORM_PRINCIPAL (DISPLAY_NAME, STATE);

ALTER TABLE KC_MANUAL_OWNER ADD PRINCIPAL_NAME VARCHAR(128);
ALTER TABLE KC_MANUAL_OWNER ADD PRINCIPAL_NAME_SYNCED_AT TIMESTAMP(6);

UPDATE KC_MANUAL_OWNER O
SET (PRINCIPAL_NAME, PRINCIPAL_NAME_SYNCED_AT) = (
  SELECT P.DISPLAY_NAME, CURRENT_TIMESTAMP
  FROM KC_PLATFORM_PRINCIPAL P
  WHERE P.PRINCIPAL_ID = O.PRINCIPAL_ID
)
WHERE EXISTS (
  SELECT 1 FROM KC_PLATFORM_PRINCIPAL P WHERE P.PRINCIPAL_ID = O.PRINCIPAL_ID
);

ALTER TABLE KC_MANUAL_OWNER MODIFY PRINCIPAL_NAME VARCHAR(128) NOT NULL;
ALTER TABLE KC_MANUAL_OWNER MODIFY PRINCIPAL_NAME_SYNCED_AT TIMESTAMP(6) NOT NULL;

COMMENT ON TABLE KC_PLATFORM_PRINCIPAL IS
  '知识中心本地人员主数据，CAS登录名为唯一且不回收的外部身份';
COMMENT ON COLUMN KC_PLATFORM_PRINCIPAL.CAS_LOGIN_NAME IS
  'CAS唯一登录名，首次登录前可为空';
COMMENT ON COLUMN KC_MANUAL_OWNER.PRINCIPAL_NAME IS
  '责任人展示姓名快照，业务关联仍以PRINCIPAL_ID为准';

