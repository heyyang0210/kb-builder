ALTER TABLE KC_MANUAL ADD PRODUCT_NAME VARCHAR(128);

UPDATE KC_MANUAL
SET PRODUCT_NAME = CASE PRODUCT_ID
  WHEN 1 THEN 'DB'
  WHEN 2 THEN 'YMP'
  WHEN 3 THEN 'YCM'
  WHEN 4 THEN 'YDC'
  ELSE CAST(PRODUCT_ID AS VARCHAR(128))
END
WHERE PRODUCT_NAME IS NULL;

