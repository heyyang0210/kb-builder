CREATE TABLE MANUAL_OUTLINE_NODE_DOMAINS (
  ID VARCHAR(256) PRIMARY KEY,
  MANUAL_ID VARCHAR(128) NOT NULL,
  OUTLINE_VERSION_ID VARCHAR(128) NOT NULL,
  NODE_ID VARCHAR(256) NOT NULL,
  TECH_DOMAIN_ID VARCHAR(128) NOT NULL,
  ASSIGNMENT_SOURCE VARCHAR(32) DEFAULT 'explicit' NOT NULL,
  ASSIGNED_BY VARCHAR(128),
  CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
  UPDATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
  CONSTRAINT CK_NODE_DOMAIN_SOURCE CHECK (ASSIGNMENT_SOURCE IN ('explicit', 'inherited')),
  CONSTRAINT UK_NODE_DOMAIN UNIQUE (OUTLINE_VERSION_ID, NODE_ID, TECH_DOMAIN_ID)
);
