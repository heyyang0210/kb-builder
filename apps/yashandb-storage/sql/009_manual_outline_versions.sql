CREATE TABLE MANUAL_OUTLINE_VERSIONS (
  ID VARCHAR(128) PRIMARY KEY,
  MANUAL_ID VARCHAR(128) NOT NULL,
  VERSION_CODE VARCHAR(128) NOT NULL,
  NAME VARCHAR(255) NOT NULL,
  STATE VARCHAR(64) NOT NULL,
  BASE_VERSION_ID VARCHAR(128),
  SOURCE_TYPE VARCHAR(64),
  SOURCE_FINGERPRINT CHAR(64),
  PARSER_VERSION VARCHAR(64),
  RULE_VERSION VARCHAR(64),
  EDIT_VERSION BIGINT DEFAULT 1 NOT NULL,
  PUBLISHED_AT VARCHAR(64),
  LEGACY_PAYLOAD CLOB,
  CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
  UPDATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
  CONSTRAINT UK_OUTLINE_VERSION_MANUAL_CODE UNIQUE (MANUAL_ID, VERSION_CODE)
);
