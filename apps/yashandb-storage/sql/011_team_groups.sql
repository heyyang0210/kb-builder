-- 团队小组与技术领域分工前置能力
-- 设计版本：1.0.0
-- 当前唯一关系为技术领域团队，直接保存在 KC_TEAM_GROUP.TECH_DOMAIN_ID。

CREATE TABLE KC_TEAM_GROUP (
  TEAM_GROUP_ID BIGINT DEFAULT KC_RESPONSIBILITY_SEQ.NEXTVAL NOT NULL,
  GROUP_CODE VARCHAR(128) NOT NULL,
  GROUP_NAME VARCHAR(255) NOT NULL,
  GROUP_TYPE VARCHAR(64) DEFAULT 'TECH_DOMAIN' NOT NULL,
  TECH_DOMAIN_ID BIGINT NOT NULL,
  ORG_UNIT_ID BIGINT,
  STATE VARCHAR(16) DEFAULT 'ACTIVE' NOT NULL,
  ROW_VERSION BIGINT DEFAULT 1 NOT NULL,
  CREATED_BY VARCHAR(128) NOT NULL,
  CREATED_AT TIMESTAMP(6) DEFAULT CURRENT_TIMESTAMP NOT NULL,
  UPDATED_BY VARCHAR(128) NOT NULL,
  UPDATED_AT TIMESTAMP(6) DEFAULT CURRENT_TIMESTAMP NOT NULL,
  CONSTRAINT PK_KC_TEAM_GROUP PRIMARY KEY (TEAM_GROUP_ID),
  CONSTRAINT UK_KC_TGROUP_CODE UNIQUE (GROUP_TYPE, GROUP_CODE),
  CONSTRAINT UK_KC_TGROUP_DOMAIN UNIQUE (GROUP_TYPE, TECH_DOMAIN_ID),
  CONSTRAINT CK_KC_TGROUP_TYPE CHECK (GROUP_TYPE = 'TECH_DOMAIN'),
  CONSTRAINT CK_KC_TGROUP_STATE CHECK (STATE IN ('ACTIVE', 'INACTIVE')),
  CONSTRAINT CK_KC_TGROUP_ROWVER CHECK (ROW_VERSION >= 1)
);

CREATE TABLE KC_TEAM_GROUP_MEMBER (
  TEAM_GROUP_MEMBER_ID BIGINT DEFAULT KC_RESPONSIBILITY_SEQ.NEXTVAL NOT NULL,
  TEAM_GROUP_ID BIGINT NOT NULL,
  PRINCIPAL_ID BIGINT NOT NULL,
  MEMBER_ROLE VARCHAR(16) NOT NULL,
  STATE VARCHAR(16) DEFAULT 'ACTIVE' NOT NULL,
  EFFECTIVE_FROM TIMESTAMP(6) DEFAULT CURRENT_TIMESTAMP NOT NULL,
  EFFECTIVE_TO TIMESTAMP(6),
  CREATED_BY VARCHAR(128) NOT NULL,
  CREATED_AT TIMESTAMP(6) DEFAULT CURRENT_TIMESTAMP NOT NULL,
  UPDATED_BY VARCHAR(128) NOT NULL,
  UPDATED_AT TIMESTAMP(6) DEFAULT CURRENT_TIMESTAMP NOT NULL,
  CONSTRAINT PK_KC_TGROUP_MEMBER PRIMARY KEY (TEAM_GROUP_MEMBER_ID),
  CONSTRAINT UK_KC_TGMEMBER_PERSON UNIQUE (TEAM_GROUP_ID, PRINCIPAL_ID),
  CONSTRAINT CK_KC_TGMEMBER_ROLE CHECK (MEMBER_ROLE IN ('LEADER', 'MEMBER')),
  CONSTRAINT CK_KC_TGMEMBER_STATE CHECK (STATE IN ('ACTIVE', 'INACTIVE')),
  CONSTRAINT CK_KC_TGMEMBER_TIME CHECK (EFFECTIVE_TO IS NULL OR EFFECTIVE_TO > EFFECTIVE_FROM)
);

CREATE INDEX IX_KC_TGROUP_SCOPE ON KC_TEAM_GROUP (GROUP_TYPE, TECH_DOMAIN_ID, STATE, UPDATED_AT);
CREATE INDEX IX_KC_TGMEMBER_PERSON ON KC_TEAM_GROUP_MEMBER (PRINCIPAL_ID, STATE);
CREATE INDEX IX_KC_TGMEMBER_GROUP ON KC_TEAM_GROUP_MEMBER (TEAM_GROUP_ID, STATE, MEMBER_ROLE);

-- 从已有技术领域生成唯一团队；不会创建演示人员关系。
INSERT INTO KC_TEAM_GROUP (GROUP_CODE, GROUP_NAME, GROUP_TYPE, TECH_DOMAIN_ID, ORG_UNIT_ID, CREATED_BY, UPDATED_BY)
SELECT 'TECH_DOMAIN:' || D.DOMAIN_CODE, D.DOMAIN_NAME, 'TECH_DOMAIN', D.TECH_DOMAIN_ID, D.ORG_UNIT_ID, 'migration:011', 'migration:011'
FROM KC_TECH_DOMAIN D
WHERE D.STATE = 'ACTIVE'
  AND NOT EXISTS (SELECT 1 FROM KC_TEAM_GROUP G WHERE G.GROUP_TYPE='TECH_DOMAIN' AND G.TECH_DOMAIN_ID=D.TECH_DOMAIN_ID);

-- 旧关系仅作为一次性迁移来源；后续运行时只写新表。
INSERT INTO KC_TEAM_GROUP_MEMBER (TEAM_GROUP_ID, PRINCIPAL_ID, MEMBER_ROLE, STATE, EFFECTIVE_FROM, EFFECTIVE_TO, CREATED_BY, UPDATED_BY)
SELECT G.TEAM_GROUP_ID, M.PRINCIPAL_ID, M.MEMBER_ROLE, M.STATE, M.EFFECTIVE_FROM, M.EFFECTIVE_TO, 'migration:011', 'migration:011'
FROM KC_TECH_DOMAIN_MEMBER M
JOIN KC_TEAM_GROUP G ON G.TECH_DOMAIN_ID=M.TECH_DOMAIN_ID AND G.GROUP_TYPE='TECH_DOMAIN'
WHERE NOT EXISTS (
  SELECT 1 FROM KC_TEAM_GROUP_MEMBER X WHERE X.TEAM_GROUP_ID=G.TEAM_GROUP_ID AND X.PRINCIPAL_ID=M.PRINCIPAL_ID
);
