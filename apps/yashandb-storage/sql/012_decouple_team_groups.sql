-- 团队小组从技术领域字典解耦；由技术领域显式引用团队。
-- 保留 011 作为已执行版本，不原地修改历史迁移。
ALTER TABLE KC_TECH_DOMAIN ADD TEAM_GROUP_ID BIGINT;

UPDATE KC_TECH_DOMAIN D
SET TEAM_GROUP_ID = (
  SELECT G.TEAM_GROUP_ID
  FROM KC_TEAM_GROUP G
  WHERE G.GROUP_TYPE = 'TECH_DOMAIN'
    AND G.TECH_DOMAIN_ID = D.TECH_DOMAIN_ID
    AND G.STATE = 'ACTIVE'
);

ALTER TABLE KC_TECH_DOMAIN MODIFY TEAM_GROUP_ID BIGINT NOT NULL;
ALTER TABLE KC_TECH_DOMAIN ADD CONSTRAINT UK_KC_TDOMAIN_GROUP UNIQUE (TEAM_GROUP_ID);

ALTER TABLE KC_TEAM_GROUP DROP CONSTRAINT UK_KC_TGROUP_DOMAIN;
DROP INDEX IX_KC_TGROUP_SCOPE;
ALTER TABLE KC_TEAM_GROUP DROP COLUMN TECH_DOMAIN_ID;
CREATE INDEX IX_KC_TGROUP_SCOPE ON KC_TEAM_GROUP (GROUP_TYPE, STATE, UPDATED_AT);
